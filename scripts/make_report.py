#!/usr/bin/env python3
"""Generate docs/benchmarks.md from the measured files in results/ (no hand-copied numbers).

    python scripts/make_report.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
R = ROOT / "results"


def load(name):
    p = R / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def table(rows, cols, headers=None):
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        cells = []
        for c in cols:
            v = r.get(c)
            if isinstance(v, float):
                v = f"{v:,.4f}" if abs(v) < 10 else f"{v:,.1f}"
            elif isinstance(v, int):
                v = f"{v:,}"
            cells.append("—" if v is None else str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def main():
    parts = ["# Benchmarks", "",
             "*Developed by Ammad Aslam with AI-assisted tooling.*", "",
             "Generated by `scripts/make_report.py` from the JSON files in `results/`. "
             "Reproduce everything with `./scripts/run_benchmarks.sh`.", ""]
    sysinfo = None
    for n in ("quality", "memory", "speed"):
        d = load(n)
        if d and d.get("system"):
            sysinfo = d["system"]
            break
    if sysinfo:
        if sysinfo.get("cpu") in ("x86_64", "aarch64", "arm64", ""):  # older result files: same machine, fill in
            from featherlm.training.metrics import cpu_model
            sysinfo["cpu"] = cpu_model()
        parts += ["## Hardware and software", "",
                  f"- CPU: {sysinfo['cpu']} ({sysinfo['cpu_count_logical']} logical cores, {sysinfo['torch_threads']} torch threads)",
                  f"- RAM: {sysinfo['ram_total_mb']:,} MB total; CUDA available: {sysinfo['cuda']}",
                  f"- OS: {sysinfo['os']}; Python {sysinfo['python']}; PyTorch {sysinfo['torch']}", ""]

    nano = load("nano_comparison")
    if nano:
        parts += ["## FeatherLM Nano vs. matched Transformer (Tiny Shakespeare)", "",
                  "Same tokenizer, data, sequence length (256), batch (8×2 accumulation), optimizer, learning-rate schedule, "
                  "dropout and early-stopping rule. Parameter counts matched within 0.02%. One seed each (these runs take "
                  "~30-40 min on 2 cores). Validation metrics are from the **best** checkpoint, evaluated with `evaluate.py`.", "",
                  table(nano["rows"], ["model", "backend", "params", "steps", "best_val_step", "val_loss", "perplexity",
                                       "bits_per_byte", "top1_accuracy", "peak_train_rss_mb", "train_tokens_per_sec", "train_time_min"]),
                  ""]

    q = load("quality_summary")
    qr = load("quality")
    if q:
        spec = qr.get("spec", {}) if qr else {}
        b = spec.get("base", {})
        parts += ["## Matched-budget comparison across seeds", "",
                  f"Spec: `configs/bench_micro.yaml`. d_model={b.get('model', {}).get('d_model')}, "
                  f"{b.get('model', {}).get('n_layers')} layers, seq_len={b.get('data', {}).get('seq_len')}, "
                  f"batch={b.get('training', {}).get('batch_size')}, steps={b.get('training', {}).get('max_steps')} "
                  f"(identical token budget), seeds={spec.get('seeds')}. Final validation loss after the last step.", "",
                  table(q["rows"], ["arch", "n_seeds", "params", "val_loss_mean", "val_loss_std", "val_ppl_mean",
                                    "peak_train_rss_mb_mean", "train_tokens_per_sec_mean", "train_time_s_mean"]),
                  "", "![validation curves](../results/quality_val_loss.png)", ""]
        if qr:
            parts += ["Per-run results:", "", table(qr["rows"], ["arch", "seed", "params", "final_val_loss", "best_val_loss",
                                                                 "peak_train_rss_mb", "train_tokens_per_sec"]), ""]

    m = load("memory")
    if m:
        tr = [r for r in m["rows"] if r["mode"] == "train"]
        inf = [r for r in m["rows"] if r["mode"] == "infer"]
        parts += ["## Memory (isolated processes, random weights)", "",
                  "Peak process RSS during 3 training steps (batch 8 × 256, AdamW). `peak_over_baseline_mb` subtracts "
                  "the RSS of the freshly started Python + PyTorch process.", "",
                  table(tr, ["config", "backend", "params", "gradient_checkpointing", "peak_rss_mb", "peak_over_baseline_mb",
                             "optimizer_state_mb"]), "",
                  "Incremental decoding to a given context length (batch 1). `cache_mb` is the KV cache / recurrent state "
                  "held after the last token.", "",
                  table(inf, ["config", "backend", "context", "cache_mb", "peak_rss_mb", "peak_over_baseline_mb"]), ""]

    s = load("speed")
    if s:
        parts += ["## CPU inference speed (random weights, median of 3 runs)", "",
                  "TTFT = prefill of the prompt plus the first token. Decode = 64 further tokens with the cache.", "",
                  table(s["rows"], ["source", "backend", "params", "threads", "prompt_len", "ttft_ms", "decode_tokens_per_sec"]), ""]

    qz = load("quantization")
    if qz:
        rows = []
        for r in qz["models"]:
            rows.append({**r, "file_mb": r["file_bytes"] / 2**20, "resident_weights_mb": r["resident_weight_bytes"] / 2**20})
        parts += ["## Quantization (FeatherLM Nano, Tiny Shakespeare validation)", "",
                  "Weight-only symmetric quantization. `dequantized` expands weights to FP32 at load; `packed` keeps "
                  "int8 / packed int4 weights in memory and dequantizes per matmul (pure PyTorch, hence slower).", "",
                  table(rows, ["quantization", "runtime", "val_perplexity", "top1_agreement", "max_abs_logit_diff",
                               "decode_tokens_per_sec", "file_mb", "resident_weights_mb"]), ""]
        if "onnx" in qz:
            o = qz["onnx"]
            parts += ["ONNX export (ONNX Runtime CPU, fixed window):", "",
                      f"- max |logit diff| vs PyTorch: {o['max_abs_logit_diff_vs_pytorch']:.2e}; top-1 agreement: {o['top1_agreement']:.4f}",
                      f"- right-padding max diff at the last real position: {o['right_padding_max_diff']:.2e}",
                      f"- one full-window forward: {o['window_forward_ms']} ms; file size {o['file_bytes'] / 2**20:.1f} MB", ""]

    parts += ["## How to read these results", "",
              "- These are small models, one small dataset and short training budgets. Differences of a few hundredths "
              "of a nat are within seed noise unless the standard deviation says otherwise.",
              "- Peak RSS includes the PyTorch runtime (~0.5-0.7 GB for the CUDA-enabled wheel used here).",
              "- Throughput on 2 vCPUs is not representative of larger machines; relative comparisons are more meaningful than absolute numbers.",
              "- Energy consumption was not measured: the VM exposes no RAPL/power counters.", ""]
    (ROOT / "docs" / "benchmarks.md").write_text("\n".join(parts))
    print("wrote docs/benchmarks.md")


if __name__ == "__main__":
    main()
